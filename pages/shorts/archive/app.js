const defaultActivity = "nouns";
const params = new URLSearchParams(window.location.search);
const requestedActivity = params.get("activity") || defaultActivity;
const activityKey = activities[requestedActivity] ? requestedActivity : defaultActivity;
const activity = activities[activityKey];

const listElement = document.getElementById("activity-list");

document.title = `${activity.title} | YouTube Shorts Activity`;

const videoIds = activity.items
  ? activity.items.map((item) => item.videoId)
  : activity.videos;

function makeVideoActivity(videoId, videoIndex) {
  const section = document.createElement("section");
  const videoColumn = document.createElement("div");

  section.className = "video-activity";
  section.id = `video-${videoIndex + 1}`;
  videoColumn.className = "video-column";

  const heading = document.createElement("h2");
  heading.textContent = `Video ${videoIndex + 1}`;

  const frame = document.createElement("div");
  frame.className = "video-frame";
  const iframe = document.createElement("iframe");
  iframe.src = `https://www.youtube-nocookie.com/embed/${encodeURIComponent(videoId)}`;
  iframe.title = `${activity.title}, video ${videoIndex + 1}`;
  iframe.loading = "lazy";
  iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
  iframe.allowFullscreen = true;
  frame.append(iframe);
  videoColumn.append(heading, frame);

  section.append(videoColumn);
  return section;
}

videoIds.forEach((videoId, videoIndex) => {
  listElement.append(makeVideoActivity(videoId, videoIndex));
});
